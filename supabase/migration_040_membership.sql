-- ---------- BADGES ----------
-- rule_type decides how a badge is earned; rule_params holds its
-- numbers. null rule_type = nothing awards it (catalog only).
--   first_checkin       {}
--   checkin_count       {"count": 25}
--   checkins_in_season  {"months": [3,4,5], "count": 4}   within one season
--   unique_beers        {"count": 5, "patterns": ["ipa"]} style contains any pattern; [] = any beer
--   lifetime_points     {"points": 1000}
--   anniversary         {"years": 1}
--   tier                {"tier": "Mug Club"}              held only while on that tier
--   all_of              {"badges": ["Spring Sipper", ...]}
alter table badges
  add column rule_type text check (rule_type in
    ('first_checkin','checkin_count','checkins_in_season','unique_beers','lifetime_points','anniversary','tier','all_of')),
  add column rule_params jsonb not null default '{}';

create table member_badges (
  id uuid primary key default gen_random_uuid(),
  member_id uuid not null references members(id) on delete cascade,
  badge_id uuid not null references badges(id) on delete cascade,
  earned_at timestamptz not null default now(),
  unique (member_id, badge_id)
);

alter table member_beers enable row level security;
alter table member_badges enable row level security;

create policy "staff only member_beers" on member_beers for all using (is_staff()) with check (is_staff());
create policy "staff only member_badges" on member_badges for all using (is_staff()) with check (is_staff());

