create or replace function membership_today()
returns date as $$
  select (now() at time zone 'America/Chicago')::date;
$$ language sql stable;

-- Awards any badge the member now qualifies for and returns the names
-- of the ones just earned. 'tier' badges are also taken away when the
-- member leaves the tier; nothing else is ever revoked.
create or replace function _evaluate_member_badges(p_member uuid)
returns text[] as $$
declare
  m members%rowtype;
  b record;
  ok boolean;
  v_months int[];
  v_patterns text[];
  earned text[] := '{}';
begin
  select * into m from members where id = p_member;
  if not found then return earned; end if;

  -- all_of goes last so it sees badges earned earlier in this pass
  for b in
    select * from badges
    where is_active and rule_type is not null
    order by (rule_type = 'all_of'), name
  loop
    ok := false;

    if b.rule_type = 'first_checkin' then
      ok := exists (select 1 from check_ins where member_id = p_member);

    elsif b.rule_type = 'checkin_count' then
      ok := (select count(*) from check_ins where member_id = p_member)
            >= coalesce((b.rule_params->>'count')::int, 1);

    elsif b.rule_type = 'checkins_in_season' then
      v_months := array(select jsonb_array_elements_text(b.rule_params->'months')::int);
      if coalesce(array_length(v_months, 1), 0) > 0 then
        -- A season that wraps the new year (Dec–Feb) is grouped under
        -- the year it ends in.
        ok := exists (
          select 1
          from check_ins c
          cross join lateral (select c.checked_in_at at time zone 'America/Chicago' as t) x
          where c.member_id = p_member
            and extract(month from x.t)::int = any (v_months)
          group by extract(year from x.t)::int
            + case when v_months[1] > v_months[array_length(v_months, 1)]
                    and extract(month from x.t)::int >= v_months[1] then 1 else 0 end
          having count(*) >= coalesce((b.rule_params->>'count')::int, 1)
        );
      end if;

    elsif b.rule_type = 'unique_beers' then
      v_patterns := array(select jsonb_array_elements_text(coalesce(b.rule_params->'patterns', '[]'::jsonb)));
      ok := (
        select count(*) from member_beers mb
        where mb.member_id = p_member
          and (coalesce(array_length(v_patterns, 1), 0) = 0
               or exists (select 1 from unnest(v_patterns) p where mb.beer_style ilike '%' || p || '%'))
      ) >= coalesce((b.rule_params->>'count')::int, 1);

    elsif b.rule_type = 'lifetime_points' then
      ok := m.points_earned_lifetime >= coalesce((b.rule_params->>'points')::int, 0);

    elsif b.rule_type = 'anniversary' then
      ok := m.joined_at <= now() - make_interval(years => coalesce((b.rule_params->>'years')::int, 1));

    elsif b.rule_type = 'tier' then
      ok := exists (select 1 from tiers t where t.id = m.tier_id and t.name = b.rule_params->>'tier');
      if not ok then
        delete from member_badges where member_id = p_member and badge_id = b.id;
      end if;

    elsif b.rule_type = 'all_of' then
      ok := jsonb_array_length(coalesce(b.rule_params->'badges', '[]'::jsonb)) > 0
        and not exists (
          select 1 from jsonb_array_elements_text(b.rule_params->'badges') need(name)
          where not exists (
            select 1 from member_badges mb join badges b2 on b2.id = mb.badge_id
            where mb.member_id = p_member and b2.name = need.name
          )
        );
    end if;

    if ok then
      insert into member_badges (member_id, badge_id) values (p_member, b.id)
      on conflict (member_id, badge_id) do nothing;
      if found then earned := earned || b.name; end if;
    end if;
  end loop;

  return earned;
end;
$$ language plpgsql security definer set search_path = public;

-- The one place a balance changes. Caller holds the member row lock.
create or replace function _member_add_points(p_member uuid, p_type text, p_points int, p_notes text)
returns int as $$
declare
  v_balance int;
begin
  update members
  set points_balance = points_balance + p_points,
      points_earned_lifetime = points_earned_lifetime + greatest(p_points, 0)
  where id = p_member
  returning points_balance into v_balance;

  if v_balance < 0 then
    raise exception 'Not enough points';
  end if;

  insert into points_transactions (member_id, transaction_type, points, notes, processed_by, staff_id)
  values (p_member, p_type, p_points, nullif(trim(p_notes), ''),
          (select name from staff_profiles where id = auth.uid()), auth.uid());

  return v_balance;
end;
$$ language plpgsql security definer set search_path = public;

create or replace function _member_lock(p_member uuid)
returns members as $$
declare
  m members%rowtype;
begin
  if not is_staff() then raise exception 'Staff only'; end if;
  select * into m from members where id = p_member for update;
  if not found then raise exception 'Member not found'; end if;
  if not m.is_active then raise exception '% is deactivated', m.name; end if;
  return m;
end;
$$ language plpgsql security definer set search_path = public;

-- One check-in per member per brewery day. Which rule pays out:
-- DD mode, else first visit ever, else Wednesday / Thursday, else
-- standard. A second call the same day changes nothing and says so.
create or replace function member_check_in(p_member uuid, p_kind text default 'standard')
returns jsonb as $$
declare
  m members%rowtype;
  v_type text;
  v_rule point_rules%rowtype;
  v_points int;
  v_balance int;
  v_dow int;
begin
  m := _member_lock(p_member);

  if exists (
    select 1 from check_ins
    where member_id = p_member
      and (checked_in_at at time zone 'America/Chicago')::date = membership_today()
  ) then
    return jsonb_build_object('already', true, 'points', 0, 'balance', m.points_balance, 'new_badges', '[]'::jsonb);
  end if;

  v_dow := extract(dow from now() at time zone 'America/Chicago');
  v_type := case
    when p_kind = 'dd' then 'checkin_dd'
    when not exists (select 1 from check_ins where member_id = p_member) then 'checkin_first_visit'
    when v_dow = 3 then 'checkin_wednesday'
    when v_dow = 4 then 'checkin_thursday'
    else 'checkin_standard'
  end;

  select * into v_rule from point_rules where transaction_type = v_type;
  -- a rule switched off falls back to the standard check-in
  if not found or not v_rule.is_active then
    select * into v_rule from point_rules where transaction_type = 'checkin_standard';
    v_type := 'checkin_standard';
  end if;
  v_points := coalesce(v_rule.points, 0);

  insert into check_ins (member_id, kind, points_awarded, staff_id)
  values (p_member, case when p_kind = 'dd' then 'dd' else 'standard' end, v_points, auth.uid());

  v_balance := _member_add_points(p_member, v_type, v_points, null);

  return jsonb_build_object(
    'already', false, 'points', v_points, 'type', v_type, 'label', v_rule.label,
    'balance', v_balance, 'new_badges', to_jsonb(_evaluate_member_badges(p_member)));
end;
$$ language plpgsql security definer set search_path = public;

-- Points outside a check-in. 'manual_adjustment' takes any non-zero
-- amount and needs a reason; every other type pays its rule's value.
create or replace function member_award_points(p_member uuid, p_type text, p_points int default null, p_notes text default null)
returns jsonb as $$
declare
  m members%rowtype;
  v_rule point_rules%rowtype;
  v_points int;
  v_balance int;
begin
  m := _member_lock(p_member);

  if p_type like 'checkin_%' then
    raise exception 'Check-ins are recorded with a check-in, not an award';
  end if;

  if p_type = 'manual_adjustment' then
    if coalesce(p_points, 0) = 0 then raise exception 'Enter a points value'; end if;
    if nullif(trim(p_notes), '') is null then raise exception 'Enter a reason for the adjustment'; end if;
    v_points := p_points;
  else
    select * into v_rule from point_rules where transaction_type = p_type and is_active;
    if not found then raise exception 'No active scoring rule for %', p_type; end if;
    v_points := v_rule.points;
  end if;

  if m.points_balance + v_points < 0 then
    raise exception 'Balance cannot go below 0';
  end if;

  v_balance := _member_add_points(p_member, p_type, v_points, p_notes);

  return jsonb_build_object('points', v_points, 'balance', v_balance,
    'new_badges', to_jsonb(_evaluate_member_badges(p_member)));
end;
$$ language plpgsql security definer set search_path = public;

create or replace function member_redeem(p_member uuid, p_reward uuid, p_notes text default null)
returns jsonb as $$
declare
  m members%rowtype;
  r rewards%rowtype;
  v_used int;
  v_since timestamptz;
  v_balance int;
begin
  m := _member_lock(p_member);

  select * into r from rewards where id = p_reward;
  if not found or not r.is_active then raise exception 'That reward is not available'; end if;

  if r.paid_only and not exists (select 1 from tiers t where t.id = m.tier_id and t.rank > 0) then
    raise exception '% requires a paid membership', r.reward_name;
  end if;

  if m.points_balance < r.points_cost then
    raise exception 'Not enough points: % of % needed', m.points_balance, r.points_cost;
  end if;

  if not r.repeatable and exists (select 1 from redemptions where member_id = p_member and reward_id = r.id) then
    raise exception '% can only be redeemed once', r.reward_name;
  end if;

  if r.limit_count is not null then
    v_since := date_trunc(r.limit_period, now() at time zone 'America/Chicago') at time zone 'America/Chicago';
    select count(*) into v_used from redemptions
    where reward_id = r.id and redeemed_at >= v_since
      and (r.limit_scope = 'brewery' or member_id = p_member);
    if v_used >= r.limit_count then
      raise exception '% is limited to % per %', r.reward_name, r.limit_count,
        r.limit_period || case when r.limit_scope = 'brewery' then ', brewery-wide' else '' end;
    end if;
  end if;

  insert into redemptions (member_id, tier_id, reward_id, reward_level, reward_name, points_spent, processed_by, staff_id, notes)
  values (p_member, m.tier_id, r.id, r.level, r.reward_name, r.points_cost,
          (select name from staff_profiles where id = auth.uid()), auth.uid(), nullif(trim(p_notes), ''));

  v_balance := _member_add_points(p_member, 'redemption', -r.points_cost, r.reward_name);

  return jsonb_build_object('reward', r.reward_name, 'points', r.points_cost, 'balance', v_balance);
end;
$$ language plpgsql security definer set search_path = public;

-- Adds a beer to the member's journal. The first time pays the
-- 'beer_journal_new' rule; after that it's a no-op.
create or replace function member_log_beer(p_member uuid, p_beer uuid)
returns jsonb as $$
declare
  m members%rowtype;
  v_beer beers%rowtype;
  v_points int := 0;
  v_balance int;
begin
  m := _member_lock(p_member);
  v_balance := m.points_balance;

  select * into v_beer from beers where id = p_beer;
  if not found then raise exception 'Beer not found'; end if;

  insert into member_beers (member_id, beer_id, beer_name, beer_style)
  values (p_member, v_beer.id, v_beer.name, v_beer.style)
  on conflict (member_id, lower(beer_name)) do nothing;

  if not found then
    return jsonb_build_object('already', true, 'points', 0, 'balance', v_balance, 'new_badges', '[]'::jsonb);
  end if;

  select points into v_points from point_rules where transaction_type = 'beer_journal_new' and is_active;
  if coalesce(v_points, 0) <> 0 then
    v_balance := _member_add_points(p_member, 'beer_journal_new', v_points, v_beer.name);
  end if;

  return jsonb_build_object('already', false, 'points', coalesce(v_points, 0), 'balance', v_balance,
    'new_badges', to_jsonb(_evaluate_member_badges(p_member)));
end;
$$ language plpgsql security definer set search_path = public;

-- One free pour per member per new release. Checks the member in if
-- they haven't been today, and puts the beer in their journal.
create or replace function member_free_pour(p_member uuid, p_beer uuid)
returns jsonb as $$
declare
  m members%rowtype;
  v_beer beers%rowtype;
  v_checkin jsonb;
  v_journal jsonb;
begin
  m := _member_lock(p_member);

  select * into v_beer from beers where id = p_beer;
  if not found or v_beer.status <> 'active' or not ('new_release' = any (v_beer.badges)) then
    raise exception 'Free pours are only for new releases on the tap list';
  end if;

  if exists (select 1 from free_pours where member_id = p_member and beer_id = p_beer) then
    raise exception '% has already had a free pour of %', m.name, v_beer.name;
  end if;

  v_checkin := member_check_in(p_member, 'standard');

  insert into free_pours (member_id, beer_id, staff_id) values (p_member, p_beer, auth.uid());

  update check_ins set new_release_poured = true, free_pour_beer = v_beer.name
  where member_id = p_member
    and (checked_in_at at time zone 'America/Chicago')::date = membership_today();

  v_journal := member_log_beer(p_member, p_beer);

  return jsonb_build_object(
    'beer', v_beer.name, 'checkin', v_checkin, 'journal', v_journal,
    'balance', v_journal->'balance',
    'new_badges', (v_checkin->'new_badges') || (v_journal->'new_badges'));
end;
$$ language plpgsql security definer set search_path = public;

