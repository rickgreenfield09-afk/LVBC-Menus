-- ============================================================
-- Migration 040 — Membership program (check-ins, points, rewards,
-- free pours, beer journal, badges)
-- ============================================================
-- The membership tables have been in schema.sql since v1 as bare
-- shapes carried over from the first staff panel (lvbc-staff-panel).
-- This is the pass that makes them work, and fixes what that panel
-- got wrong:
--
--   * Points never move from the browser any more. Every earn and
--     spend goes through one of the member_* functions below, which
--     lock the member row, write the ledger line and the balance in
--     one transaction, and take the point value from point_rules —
--     so the Scoring page actually changes what a check-in is worth.
--   * One check-in per member per brewery day.
--   * A redemption names a rewards row, so disabling a reward or
--     changing its cost takes effect at the bar, and "once per month"
--     style limits are enforced instead of being a note.
--   * Badges award themselves. Each badge carries a rule
--     (rule_type + rule_params) that _evaluate_member_badges() checks
--     after anything that could earn one.
--
-- rewards.tier_id pointed at membership tiers (Free / Mug Club / ...),
-- but a reward's "tier" was always its level, 1–5. It becomes `level`,
-- and the "levels 3+ are for paying members" rule becomes paid_only.
--
-- New tables:
--   member_beers    the beer journal: each beer a member has tried,
--                   once. Fed by "Log beer" and by free pours. Name
--                   and style are snapshotted so a beer leaving the
--                   tap list doesn't erase the history badges count.
--   member_badges   who has earned what.
--
-- Free pours stay tied to the tap list: a beer is pourable when it is
-- active and carries the 'new_release' badge (beers.badges), one per
-- member per beer.
--
-- "Today" everywhere here is the brewery's day, America/Chicago.
--
-- RLS is unchanged in spirit: staff only. The functions are
-- security definer and check is_staff() themselves.

